#!/usr/bin/env python3
"""Write the landing page's sample screening: python scripts/sample_screening.py

Two fictional companies with hand-entered inputs go through the real
RatioEngine and the rule-based narrator (the same code a manual screening
uses), and the result is written to ui/lib/sample-screening.json for the
public landing page. tests/test_sample_screening.py fails when the committed
file no longer matches what the engine produces, so the sample cannot drift.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from narrator.explainer import RuleBasedNarrator  # noqa: E402
from ratio_engine import FinancialSnapshotInput, MarketDataInput, RatioEngine  # noqa: E402

OUTPUT = ROOT / "ui" / "lib" / "sample-screening.json"

# Amounts in ₹ crore. The companies and figures are invented.
COMPANIES = [
    {
        "symbol": "SAMPLE-A",
        "name": "Sample Manufacturing Ltd (fictional)",
        "market_cap": 10_000,
        "inputs": {
            "total_debt": 1_500,
            "cash_equiv": 800,
            "revenue": 6_000,
            "interest_income": 60,
            "dividend_income": 30,
            "non_permissible_income": 30,
            "accounts_receivable": 2_000,
            "liquid_assets": 1_500,
        },
    },
    {
        "symbol": "SAMPLE-B",
        "name": "Sample Leasing Finance Ltd (fictional)",
        "market_cap": 8_000,
        "inputs": {
            "total_debt": 5_200,
            "cash_equiv": 900,
            "revenue": 2_400,
            "interest_income": 700,
            "dividend_income": 20,
            "non_permissible_income": 10,
            "accounts_receivable": 3_000,
            "liquid_assets": 2_000,
        },
    },
]

FILING_DATE = datetime(2026, 3, 31)


def build() -> dict:
    engine = RatioEngine()
    narrator = RuleBasedNarrator()
    companies = []
    for company in COMPANIES:
        snapshot = FinancialSnapshotInput(
            symbol=company["symbol"], filing_date=FILING_DATE, **company["inputs"]
        )
        evaluation = engine.evaluate(snapshot, MarketDataInput(market_cap=company["market_cap"]))
        narration = narrator.build(evaluation)
        companies.append(
            {
                "symbol": company["symbol"],
                "name": company["name"],
                "market_cap": company["market_cap"],
                "inputs": company["inputs"],
                "verdict": evaluation.verdict,
                "ratios": {
                    key: {
                        "label": comp.note,
                        "value": round(comp.value, 6) if comp.value is not None else None,
                        "threshold": comp.threshold,
                        "passed": comp.passed,
                    }
                    for key, comp in evaluation.ratios.items()
                },
                "summary": narration.summary,
                "bullets": narration.bullets,
            }
        )
    return {
        "note": "Generated by scripts/sample_screening.py from fictional, hand-entered inputs. Do not edit.",
        "units": "INR crore",
        "filing_date": FILING_DATE.date().isoformat(),
        "companies": companies,
    }


def render() -> str:
    return json.dumps(build(), indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
