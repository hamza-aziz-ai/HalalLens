import clsx from "clsx";
import sample from "@/lib/sample-screening.json";
import RatioGauge from "@/components/ratio-gauge";
import { VerdictBadge, cardClass } from "@/components/ui";

export type SampleCompany = (typeof sample.companies)[number];

/** The "fictional" label every sample view carries, so a cropped screenshot still says so. */
export function SampleLabel() {
  return (
    <p className="font-mono text-[11px] font-medium uppercase tracking-wider text-warning">
      Sample data · fictional company · not live screening
    </p>
  );
}

export function SampleGauges({ company }: { company: SampleCompany }) {
  return (
    <div className="space-y-3">
      {Object.entries(company.ratios).map(([key, ratio], index) => (
        <RatioGauge
          key={key}
          label={ratio.label}
          value={ratio.value}
          threshold={ratio.threshold}
          passed={ratio.passed}
          delayMs={150 + index * 90}
        />
      ))}
    </div>
  );
}

/**
 * The landing page's worked example. The data is generated by
 * scripts/sample_screening.py (RatioEngine + rule-based narrator) and a
 * pytest keeps the committed JSON equal to the engine's output.
 */
export default function SampleScreening() {
  return (
    <div className="mt-8 grid gap-6 lg:grid-cols-2">
      {sample.companies.map((company) => (
        <article
          key={company.symbol}
          className={clsx(cardClass, "flex flex-col p-6 transition hover:border-brand/40 hover:shadow-md")}
        >
          <SampleLabel />
          <div className="mt-3 flex flex-wrap items-start justify-between gap-3">
            <div>
              <h3 className="font-semibold text-fg">{company.name}</h3>
              <p className="text-xs text-muted">
                Market cap ₹{company.market_cap.toLocaleString("en-IN")} crore · filing dated{" "}
                {sample.filing_date}
              </p>
            </div>
            <VerdictBadge verdict={company.verdict} />
          </div>
          <div className="mt-5">
            <SampleGauges company={company} />
          </div>
          <div className="mt-6 rounded-lg border border-line bg-surface-2 p-4">
            <p className="font-mono text-[11px] font-medium uppercase tracking-wider text-brand">Explain-Why</p>
            <p className="mt-2 text-sm text-fg">{company.summary}</p>
            <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-muted">
              {company.bullets.map((bullet) => (
                <li key={bullet}>{bullet}</li>
              ))}
            </ul>
          </div>
        </article>
      ))}
    </div>
  );
}
